# TAB 2: Guardrail Red Team Playground
# ==========================================
with tab_guardrails:
    st.subheader("🛡️ AST Query Guardrail & Attack Defense Playground")
    st.markdown("Test malicious, destructive, or unauthorized SQL payloads to observe the multi-tier AST validator in action.")

    attack_payloads = {
        "Destructive DROP TABLE": "DROP TABLE customers;",
        "Destructive DELETE Mutation": "DELETE FROM orders WHERE 1=1;",
        "Unauthorized UPDATE Mutation": "UPDATE products SET unit_price = 0.01 WHERE category = 'Electronics';",
        "Stacked Query Semicolon Piggybacking": "SELECT * FROM customers; DROP TABLE suppliers;",
        "Tautology SQL Injection Bypass": "SELECT * FROM customers WHERE 1=1 OR 'a'='a';",
        "System Schema Catalog Exploit": "SELECT * FROM sqlite_master;",
        "Dangerous Dialect Procedure (ATTACH)": "ATTACH DATABASE 'malicious.db' AS evil;",
        "Safe Multi-Table Join Query": "SELECT c.first_name, o.order_id, p.product_name FROM customers c JOIN orders o ON c.customer_id = o.customer_id JOIN order_items oi ON o.order_id = oi.order_id JOIN products p ON oi.product_id = p.product_id WHERE o.status = 'Delivered';"
    }

    selected_attack = st.selectbox("Select Pre-loaded Security Test Scenario:", list(attack_payloads.keys()))
    attack_sql = st.text_area("SQL Statement to Audit:", value=attack_payloads[selected_attack], height=120)

    if st.button("🔍 Run AST Security Audit", type="primary"):
        audit_res: GuardrailAudit = guardrails.validate_and_sanitize(attack_sql)

        if audit_res.is_safe:
            st.markdown('<span class="badge-safe">✅ 100% SAFE: Query Passed All Guardrails</span>', unsafe_allow_html=True)
            st.success("Query was validated and is safe for read-only sandboxed execution.")
            st.markdown(f"**Sanitized SQL (Limit Enforced)**:\n```sql\n{audit_res.sanitized_sql}\n```")
        else:
            st.markdown('<span class="badge-blocked">🚨 THREAT DETECTED: 100% BLOCKED</span>', unsafe_allow_html=True)
            st.error(f"**Risk Level**: `{audit_res.risk_level}`")
            st.markdown("##### Violations Detected:")
            for v in audit_res.violations:
                st.markdown(f"- 🛑 **{v}**")

        st.markdown("##### 🔬 AST Node Metadata")
        col_m1, col_m2, col_m3, col_m4 = st.columns(4)
        col_m1.metric("Root AST Node", audit_res.ast_type)
        col_m2.metric("JOIN Count", audit_res.join_count)
        col_m3.metric("Subquery Depth", audit_res.subquery_depth)
        col_m4.metric("Risk Level", audit_res.risk_level)

